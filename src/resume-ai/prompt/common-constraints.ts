export const commonHtmlRules = `
【HTML 标签使用规范】
以下字段的内容必须使用 HTML 标签进行格式化，以突出关键词、成果或数据，但避免过度装饰：

使用规则：

1. **强制列表化**：以下字段**必须**强制使用 \`<ul><li>...</li></ul>\` 结构呈现所有可枚举信息。禁止使用纯文本段落（\`<p>\`）。

2. **长度限制**：禁止出现任何超过 80 个字符的连续纯文本行。若内容过长，**必须**在下一行直接使用单个 \`<li>\` 标签包裹，**严禁**使用嵌套列表结构（如 \`<ul><li>...<ul>...\`），确保视觉整洁。

3. **关键词高亮**：核心技能、关键成果、量化数据（如百分比、数字）使用 \`<strong>...</strong>\` 加粗。

4. **样式**：可酌情使用 <span style="..."> 进行背景色强调。

5. **技能修饰**：在生成技能内容时，**必须**为技能添加熟练度修饰词（如"精通"、"熟练掌握"、"熟悉"、"了解"）。例如：<li>熟练掌握 Vue3 全家桶...</li>。

6. **证书判空**：若候选人无证书或原始经历未提及，证书字段必须严格返回空字符串 ""，禁止生成任何占位描述（如"暂无证书"）。
`;

